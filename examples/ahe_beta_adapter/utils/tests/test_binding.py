"""Tested adapter bindings compare content, not unrelated repository commit IDs."""

from pathlib import Path
import sys
import subprocess
import pytest

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from binding import fingerprint, read, write


def test_binding_rejects_different_bytes_and_ignores_generated_card(tmp_path):
    repo = tmp_path / "repo"
    repo.mkdir()
    (repo / "ADAPTER.md").write_text("Inspect and solve.")

    def git(*args):
        subprocess.run(["git", "-C", str(repo), *args], check=True, capture_output=True)

    git("init", "-b", "main")
    git("config", "user.name", "Test")
    git("config", "user.email", "test@example.invalid")
    git("add", ".")
    git("commit", "-m", "fixture")
    binding = tmp_path / "binding.json"
    expected = write(binding, adapter=repo, repo=repo, run_id="run", round_no=1)
    assert read(binding, repo) == expected
    (repo / ".hermit").mkdir()
    (repo / ".hermit/CARD.md").write_text("Generated by the Trainer")
    assert read(binding, repo) == expected
    (repo / "ADAPTER.md").write_text("Changed")
    with pytest.raises(ValueError, match="differs"):
        read(binding, repo)


def test_the_fingerprint_keeps_only_the_executable_bit_git_keeps(tmp_path):
    """The Trainer exports the rollout's adapter through git archive and tar under this process's umask: a script 0700
    here may be 0755 there, and the next round's sessions refused the commit that was delivered."""
    (tmp_path / "ADAPTER.md").write_text("x")
    (tmp_path / "run.sh").write_text("#!/bin/sh\n")
    (tmp_path / "run.sh").chmod(0o700)
    executable = fingerprint(tmp_path)
    (tmp_path / "run.sh").chmod(0o755)
    assert fingerprint(tmp_path) == executable
    (tmp_path / "run.sh").chmod(0o644)
    assert fingerprint(tmp_path) != executable
