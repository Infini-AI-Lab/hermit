"""Emit an OpenCode configuration: an `opencode.json` plus the `.opencode/` tree of the project it is read in.

OpenCode reads its configuration, skills and subagents from the project directory it is opened in, and that carries
every part of an adapter:

- context: `.opencode/context.md`, listed in `opencode.json`'s `instructions`. OpenCode combines every instruction
  file with the project's own `AGENTS.md`, so a project that already has rules keeps them.
- tools: an entry in `opencode.json`'s `mcp` map: a server of type `local`, started as `hermit serve`.
- skills: `.opencode/skills/`, the directory OpenCode discovers `skills/*/SKILL.md` from.
- roles: `.opencode/agents/*.md`, where the file name is the agent's name and the frontmatter makes it a subagent
  (`mode: subagent`).

OpenCode expands no plugin-root variable, so the tool entry may not name an absolute path: it runs the server from
the workspace (`cwd`) and names the embedded adapter from there, which is the layout this emitter writes at the
project root. The audit log lives under `.opencode/audit/`, outside the adapter, which `Session` requires.
"""
from __future__ import annotations

from pathlib import Path
import json

from hermit.plugins.common import (ADAPTER_DIR, AUDIT_LOG, FRAMEWORK_VERSION, RECORD, SERVER_COMMAND, clear,
                                           copy_skills, embed_adapter, load, prepare_output, record, role_body,
                                           server_args, subagent_name, write_json)

SCHEMA = "https://opencode.ai/config.json"
CONFIG = "opencode.json"
DIR = ".opencode"
CONTEXT = f"{DIR}/context.md"
AUDIT_DIR = f"{DIR}/audit"


def agent_file(role: dict, instructions: str) -> tuple[str, str]:
    """A role as an OpenCode subagent. The file name is the agent's name, so the frontmatter carries only what
    OpenCode does not derive from it."""
    native = subagent_name(role["name"])
    return native, (f"---\ndescription: {json.dumps(role['description'])}\nmode: subagent\n---\n\n"
                    f"{instructions.strip()}\n")


def build(adapter: Path, output: Path, python: str, *, allow_lossy: bool = False) -> dict:
    bundle = load(adapter, python)
    output = prepare_output(output, bundle.adapter, RECORD)
    # Only the generated entries: the audit log of an earlier conversion is the user's and stays.
    clear(output, f"{DIR}/skills", f"{DIR}/agents", CONTEXT)

    roles = {}
    for role in bundle.roles:
        native, text = agent_file(role, role_body(bundle.adapter, role))
        (output / DIR / "agents").mkdir(parents=True, exist_ok=True)
        (output / DIR / "agents" / f"{native}.md").write_text(text)
        roles[role["name"]] = native

    context = bundle.context
    for name, native in roles.items():
        context = context.replace(f"`{name}`", f"`{native}`")   # as `deploy --host claude-code` does

    config = {"$schema": SCHEMA}
    if bundle.has_context:
        (output / CONTEXT).parent.mkdir(parents=True, exist_ok=True)
        (output / CONTEXT).write_text(context.strip() + "\n")
        config["instructions"] = [CONTEXT]
    if bundle.tools:
        (output / AUDIT_DIR).mkdir(parents=True, exist_ok=True)
        config["mcp"] = {bundle.server: {
            "type": "local", "command": [SERVER_COMMAND] + server_args(ADAPTER_DIR, f"{AUDIT_DIR}/{AUDIT_LOG}"),
            "cwd": ".", "enabled": True}}
    write_json(output / CONFIG, config)

    skills = copy_skills(bundle, output / DIR / "skills")
    embed_adapter(bundle, output)
    record(bundle, output)
    (output / "README.md").write_text(_readme(bundle, output, skills, roles))
    return {"target": "opencode", "adapter_id": bundle.id, "version": bundle.version,
            "framework": FRAMEWORK_VERSION, "output": str(output), "plugin": str(output),
            "install": [f"cp -R {output}/. /path/to/your/project/", "cd /path/to/your/project && opencode"],
            "context": CONTEXT if bundle.has_context else None,
            "skills": skills, "roles": roles,
            "server_name": bundle.server if bundle.tools else None, "omitted": []}


def _readme(bundle, output: Path, skills: list, roles: dict) -> str:
    return "\n".join([
        f"# {bundle.name}", "",
        f"An OpenCode configuration generated by `hermit convert` from the `{bundle.id}` adapter, version "
        f"{bundle.version}.", "", "```", f"cp -R {output}/. /path/to/your/project/",
        "cd /path/to/your/project && opencode", "```", "",
        "OpenCode reads these files from the project it is opened in, so they belong at that project's root.", "",
        "The tools run as `hermit serve`, so `hermit` must be installed and on PATH.", "",
        "- Context: `.opencode/context.md`, combined with the project's own `AGENTS.md` through `instructions`."
        if bundle.has_context else "- Context: none",
        f"- Skills: {', '.join(skills) or 'none'}",
        f"- Roles: {', '.join(roles.values()) or 'none'}" + (f" in `{DIR}/agents/`" if roles else ""),
        f"- Tools: {', '.join(t['name'] for t in bundle.tools) or 'none'}"
        + (f", served as `{bundle.server}`" if bundle.tools else ""), ""])
