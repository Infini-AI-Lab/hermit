"""Emit an OpenClaw workspace plugin bundle: embedded adapter, skills/, AGENTS.md context, and openclaw.run.json.

OpenClaw workspace plugins carry context (AGENTS.md), skills (skills/<name>/SKILL.md), and MCP tools
(configured via `hermit serve` in openclaw.run.json). Roles and hooks are refused unless --allow-lossy is passed.
"""
from __future__ import annotations

from pathlib import Path

from hermit.plugins.common import (
    ADAPTER_DIR, AUDIT_LOG, FRAMEWORK_VERSION, RECORD, SERVER_COMMAND,
    clear, copy_skills, embed_adapter, load, prepare_output, record, refuse, server_args, write_json
)
from hermit.hosts.openclaw import validate_openclaw_skills


def build(adapter: Path, output: Path, python: str, *, allow_lossy: bool = False) -> dict:
    bundle = load(adapter, python)
    reasons = {}
    if bundle.roles:
        role_names = ", ".join(r["name"] for r in bundle.roles)
        reasons["roles"] = f"OpenClaw v1 has no subagent role files ({role_names})"
    omitted = refuse(bundle, "OpenClaw", reasons, allow_lossy=allow_lossy)
    validate_openclaw_skills(bundle.adapter, bundle.manifest)
    output = prepare_output(output, bundle.adapter, RECORD)
    clear(output, "skills", "AGENTS.md", "openclaw.run.json")

    if bundle.has_context and "context" not in omitted:
        (output / "AGENTS.md").write_text(bundle.context.strip() + "\n", encoding="utf-8")

    skills = copy_skills(bundle, output / "skills")
    embed_adapter(bundle, output)
    record(bundle, output)

    run_config = {
        "skills": {"workshop": {"autonomous": {"mode": "off"}}},
        "tools": {"deny": ["skill_workshop"]}
    }
    if bundle.tools:
        run_config["mcp"] = {
            "servers": {
                bundle.server: {
                    "command": SERVER_COMMAND,
                    "args": server_args(str(output / ADAPTER_DIR), str(output / AUDIT_LOG))
                }
            }
        }
    write_json(output / "openclaw.run.json", run_config)

    cfg_file = output / "openclaw.run.json"
    skills_str = ", ".join(skills) or "none"
    tools_str = ", ".join(t["name"] for t in bundle.tools) or "none"
    omitted_str = ", ".join(omitted)

    (output / "README.md").write_text("\n".join([
        f"# {bundle.name}", "",
        f"An OpenClaw plugin bundle generated by `hermit convert` from the `{bundle.id}` adapter, version {bundle.version}.", "",
        "```",
        f"openclaw agent exec --cwd {output} --config {cfg_file}",
        "```", "",
        "The tools run as `hermit serve`, so `hermit` must be installed and on PATH.", "",
        f"- Context: `AGENTS.md` ({len(bundle.context.strip()):,} chars)" if (output / "AGENTS.md").is_file() else "- Context: none",
        f"- Skills: {skills_str}",
        f"- Tools: {tools_str}",
        f"- Left out (--allow-lossy): {omitted_str}" if omitted else "- Left out: nothing", ""
    ]), encoding="utf-8")

    return {
        "target": "openclaw",
        "adapter_id": bundle.id,
        "version": bundle.version,
        "framework": FRAMEWORK_VERSION,
        "output": str(output),
        "install": [f"openclaw agent exec --cwd {output} --config {cfg_file}"],
        "context": "AGENTS.md" if (output / "AGENTS.md").is_file() else None,
        "skills": skills,
        "server_name": bundle.server if bundle.tools else None,
        "omitted": omitted
    }
