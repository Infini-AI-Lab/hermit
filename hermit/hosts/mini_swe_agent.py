#!/usr/bin/env python3
"""Deploy an adapter into a mini-swe-agent workspace: the whole adapter under hermit/<id>/, and its exports
connected to mini-swe-agent's one place, the config file `mini-swe-agent.yaml`.

mini-swe-agent (https://mini-swe-agent.com) reads no instructions file and has no plugins, sub-agents, skills, hooks
or MCP client: one YAML config's Jinja templates make its first two messages, and its model runs bash commands only.
So the config is Hermit's prompts over mini-swe-agent's own `mini` config (hermit.agent.base.mini_swe_agent), with
the adapter's context, the files it names and its tools written into the system template. The context names the
skills, roles, hooks and other files of the adapter's copy with what to do with them (hermit.hosts.inputs.resources),
as Pi's AGENTS.md does. The tools are one command, `hermit-tool <name> '<JSON arguments>'`, answered in
mini-swe-agent's process by hermit.hosts.mini_swe_agent_env.AdapterEnvironment, which the config then names as its
environment class: mini-swe-agent must run in the Python environment hermit is installed in. An adapter without
tools keeps mini-swe-agent's `local` environment.

Run it from the workspace with `mini -c mini-swe-agent.yaml -m <model>`. The `mini-swe-agent` Base Agent reads the
same file's `hermit.context` and builds the same system message from Hermit's prompts, so an agent in training and
a deployed one read the same text (the Base Agent's own `model_class` and `config` are not deployed). Global
mini-swe-agent settings are never changed.
"""
import argparse
import json
from pathlib import Path
import sys

import yaml

from hermit.adapter.loader import agent_tools, hook_definitions, load_manifest, not_portable
from hermit.agent.base.mini_swe_agent import CONFIG_FILE, adapter_block, baked, render_config, tools_section
from hermit.hosts.inputs import (MARKER, add_session_flags, adapter_files, adapter_folder, check_workspace,
                                 context_of, copy_adapter, folder_note, render_exports, resources, source_label)

HOST = "mini-swe-agent"
NATIVE: set[str] = set()                  # neither skills nor roles: the context names them
ENVIRONMENT_CLASS = "hermit.hosts.mini_swe_agent_env.AdapterEnvironment"


class _Dumper(yaml.SafeDumper):
    pass


_Dumper.add_representer(str, lambda dumper, value: dumper.represent_scalar(
    "tag:yaml.org,2002:str", value, style="|" if "\n" in value else None))


def prepare(adapter: Path, output: Path, python: str, *, learning_material: Path | None = None,
            context: str | None = None, serve_tools: bool = True) -> dict:
    """`context`: the adapter's context for one task, which the harness computed, in place of the one rendered
    here; an adapter whose context is per task deploys only so. `serve_tools`: false when the caller serves the
    adapter's tools to the session itself (the `mini-swe-agent` Base Agent): the config then names no tools."""
    adapter, output = adapter.resolve(), output.resolve()
    refused = not_portable(load_manifest(adapter), "A mini-swe-agent workspace")   # before anything is written
    if refused and context is None:
        raise ValueError(refused)
    previous = check_workspace(adapter, output, HOST)
    manifest = load_manifest(adapter)
    try:
        config = render_config("mini")
    except RuntimeError as error:                 # mini-swe-agent is not installed
        raise ValueError(str(error)) from None
    files = adapter_files(adapter, output, manifest, previous)
    exports = render_exports(adapter, python)
    listed, placed = resources(adapter, output, manifest, exports, hook_definitions(adapter, manifest), NATIVE)
    text = "\n\n".join(t for t in (folder_note(output, manifest),
                                    exports["context"] if context is None else context, listed) if t)
    tools = agent_tools(manifest) if serve_tools else []     # the context tool is the harness's, not served
    config["agent"]["system_template"] = baked(config["agent"]["system_template"],
                                               adapter_block(text, tools_section(tools)))
    audit = output / "tool-calls.jsonl"
    if tools:
        config["environment"] = {**config.get("environment", {}), "environment_class": ENVIRONMENT_CLASS,
                                 "adapter": str(adapter), "audit_log": str(audit)}
        if learning_material is not None:
            config["environment"]["learning_material"] = str(Path(learning_material).resolve())
    config["hermit"] = {"context": text}            # what the Base Agent reads (mini-swe-agent ignores the key)
    output.mkdir(parents=True, exist_ok=True)
    header = (f"# Generated by hermit for the adapter {manifest['id']} {manifest['version']} "
              f"({source_label(manifest)}). No global settings are changed.\n"
              "# Run from this directory: mini -c mini-swe-agent.yaml -m <model>\n")
    (output / CONFIG_FILE).write_text(header + yaml.dump(config, Dumper=_Dumper, sort_keys=False, allow_unicode=True,
                                                         width=10_000))
    copy_adapter(adapter, output, manifest, files, previous)
    result = {"host": HOST, "adapter_id": manifest["id"], "version": manifest["version"], "adapter": str(adapter),
              "workspace": str(output), "context_injected_via": CONFIG_FILE,
              "environment_class": ENVIRONMENT_CLASS if tools else "local", "tools": [t["name"] for t in tools],
              "roles": {}, "role_name_map": {}, "skills_dir": None, "skills": [], "hooks": None,
              "audit_log": str(audit) if tools else None, "adapter_dir": str(adapter_folder(output, manifest)),
              "files": files, "placed": placed,
              "command": [python, "-m", "minisweagent", "-c", CONFIG_FILE, "-m", "<model>"]}
    (output / MARKER).write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n")
    return result


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--adapter", type=Path, required=True)
    parser.add_argument("--workspace", "--output", dest="workspace", type=Path, required=True)
    parser.add_argument("--python", default=sys.executable)
    add_session_flags(parser)
    args = parser.parse_args()
    print(json.dumps(prepare(args.adapter, args.workspace, str(Path(args.python).absolute()),
                             context=context_of(args.context_file), serve_tools=args.serve_tools),
                     ensure_ascii=False, indent=2))
