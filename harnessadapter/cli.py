"""The harnessadapter command: deploy an adapter to an acting host, run an
evolution session, or drive either from launch YAML.

    harnessadapter deploy mwm --host codex
    harnessadapter evolve mwm --learning-material ./learning-material --backend codex
    harnessadapter run config/evolve.yaml --dry-run

`harnessadapter <adapter> [--codex|--claude]` is the deploy form without
the subcommand, kept from the repository-local script this replaced.
"""
import argparse
from pathlib import Path
import shlex
import shutil
import subprocess
import sys

from harnessadapter.paths import resolve_architecture, workspace_root


def _deploy(argv):
    parser = argparse.ArgumentParser(
        prog="harnessadapter deploy",
        description="Prepare an adapter for Codex or Claude Code. The host starts MCP automatically.")
    parser.add_argument("adapter", help="prompt-only, mwm, minimal-shop, or a local adapter repo path")
    material = parser.add_mutually_exclusive_group(required=False)
    material.add_argument("--learning-material", dest="evidence", type=Path, help="Read-only LearningMaterial directory with README.md")
    material.add_argument("--evidence", dest="evidence", type=Path, help="Compatibility alias for --learning-material")
    parser.add_argument("--host", choices=["codex", "claude-code"], help="Target host (default: codex)")
    parser.add_argument("--prepare-only", action="store_true", help="Prepare host files without launching")
    launch = parser.add_mutually_exclusive_group()
    launch.add_argument("--codex", action="store_true", help="Prepare and open Codex")
    launch.add_argument("--claude", action="store_true", help="Prepare and open Claude Code")
    parser.add_argument("--workspace", "--workdir", dest="workspace", type=Path,
                        help="Dedicated generated workspace (default: .demo/<adapter>/<host>)")
    args = parser.parse_args(argv)
    inferred_host = "claude-code" if args.claude else "codex" if args.codex else None
    if args.host and inferred_host and args.host != inferred_host:
        parser.error("The host and launch shortcut must agree")
    host = args.host or inferred_host or "codex"
    executable = "claude" if host == "claude-code" else "codex"
    launch_host = (args.codex or args.claude) and not args.prepare_only
    if launch_host and not shutil.which(executable):
        parser.error(f"{executable} is not on PATH. Install it and sign in before launching.")

    if host == "claude-code":
        from harnessadapter.hosts.claude_code import MARKER, prepare
    else:
        from harnessadapter.hosts.codex import MARKER, prepare
    from harnessadapter.adapter.loader import load_manifest
    from harnessadapter.hosts.inputs import adapter_id

    adapter = resolve_architecture(args.adapter).resolve()
    manifest = load_manifest(adapter)
    identity = adapter_id(manifest)
    default_workspace = workspace_root() / executable if identity == "minimal-shop" else workspace_root() / identity / executable
    workspace = (args.workspace or default_workspace).resolve()
    if workspace == adapter or adapter in workspace.parents or workspace in adapter.parents:
        parser.error("The generated workspace must be separate from adapter source")
    if workspace.exists() and any(workspace.iterdir()) and not (workspace / MARKER).is_file():
        parser.error("Choose an empty workspace or one previously generated by this tool")

    info = prepare(adapter, workspace, sys.executable, learning_material=args.evidence)
    try:
        display_path = str(workspace.relative_to(Path.cwd())) or "."
    except ValueError:
        display_path = str(workspace)
    command_text = (f"cd {shlex.quote(display_path)} && claude" if host == "claude-code"
                    else shlex.join(["codex", "-C", display_path]))
    print(f"\nReady: {identity}", flush=True)
    context_file = "CLAUDE.md" if host == "claude-code" else "AGENTS.md"
    mcp_status = f"{info['server_name']} (started by {executable})" if info["server"] else "none (context-only adapter)"
    print(f"  Context: {context_file}\n  MCP: {mcp_status}\n  Native roles: {', '.join(info['roles']) or '(none)'}", flush=True)
    print(f"\nOpen {executable}:\n  {command_text}", flush=True)
    print("\nThen ask: Run the adapter integration task in PROMPT.md.", flush=True)
    print("The host must trust the workspace." + (" Approve/load its MCP configuration when prompted." if info["server"] else " No adapter MCP server is registered.") + " No global settings were changed.", flush=True)
    if launch_host:
        # Preserve the user's normal model, permissions, approval, and login settings.
        command = ["claude"] if host == "claude-code" else ["codex", "-C", str(workspace)]
        raise SystemExit(subprocess.call(command, cwd=workspace))


def main(argv=None):
    argv = list(sys.argv[1:] if argv is None else argv)
    if sys.version_info < (3, 11):
        raise SystemExit("harnessadapter: Python 3.11 or newer is required")
    try:
        if argv[:1] == ["evolve"]:
            from harnessadapter.evolution.session import main as evolve_main
            return evolve_main(argv[1:])
        if argv[:1] == ["run"]:
            from harnessadapter.evolution.launch import main as launch_main
            return launch_main(argv[1:])
        if argv[:1] == ["deploy"]:
            argv = argv[1:]
        if argv[:1] in (["-h"], ["--help"], []):
            print(__doc__.strip())
            print("\nSubcommands: deploy (default), evolve, run. Add -h after one for its options.")
            return 0
        return _deploy(argv)
    except KeyboardInterrupt:
        raise SystemExit(130)
    except (ValueError, OSError, subprocess.CalledProcessError) as exc:
        print(f"harnessadapter: {exc}", file=sys.stderr)
        raise SystemExit(1)
