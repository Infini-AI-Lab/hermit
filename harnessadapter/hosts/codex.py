#!/usr/bin/env python3
"""Deploy an adapter's exports into a Codex workspace: AGENTS.md context, MCP tools, native roles, skills.

Global Codex settings are never changed; everything goes into the workspace (.codex/).
"""
import argparse
import json
from pathlib import Path
import re
import subprocess
import sys
import tomllib

from harnessadapter.adapter.loader import load_manifest
from harnessadapter.hosts.context import PROJECT_CONTEXT, append_context
from harnessadapter.hosts.inputs import (MARKER, PACKAGE_ROOT, check_workspace, copy_skills, render_exports, retire_roles,
                                         role_body, server_name, source_label)


def _toml(value) -> str:
    if isinstance(value, dict):
        return "{ " + ", ".join(f"{k} = {_toml(v)}" for k, v in value.items()) + " }"
    return json.dumps(value, ensure_ascii=False)


def prepare(adapter: Path, output: Path, python: str, *, learning_material: Path | None = None) -> dict:
    adapter, output = adapter.resolve(), output.resolve()
    previous = check_workspace(adapter, output, "codex")
    output.mkdir(parents=True, exist_ok=True)
    manifest = load_manifest(adapter)
    exports = render_exports(adapter, python)
    context = exports["context"]
    roles = [{**r, "name": r["name"].replace("-", "_")} for r in exports["agents"]]
    role_name_map = {r["name"]: r["name"].replace("-", "_") for r in exports["agents"]}
    if any(k != v for k, v in role_name_map.items()):
        context += "\n\nNative role mapping: " + ", ".join(f"{k} → {v}" for k, v in role_name_map.items())
    names = [r["name"] for r in roles]
    if len(set(names)) != len(names) or any(not re.fullmatch(r"[a-z][a-z0-9_]{0,63}", n) for n in names):
        raise ValueError("Agent names must be unique, lowercase Codex identifiers")
    context_path = output / "AGENTS.md"
    existing = context_path.read_text() if context_path.exists() else PROJECT_CONTEXT
    context_text = append_context(existing, context, source=source_label(manifest), version=manifest["version"],
                                  adapter_id=manifest["id"])
    has_tools = bool(manifest.get("tools"))
    if has_tools:
        subprocess.run([python, "-c", "import mcp.server"], check=True, capture_output=True)
    agents_dir = output / ".codex" / "agents"
    agents_dir.mkdir(parents=True, exist_ok=True)
    audit = output / "tool-calls.jsonl"
    server = None
    config = ["# Generated by harnessadapter. No global settings are changed."]
    if has_tools:
        server = {"command": python, "args": ["-m", "harnessadapter.runtime.mcp_server", "--adapter", str(adapter),
                                              "--audit-log", str(audit)],
                  "env": {"PYTHONPATH": PACKAGE_ROOT},
                  "startup_timeout_sec": 20, "tool_timeout_sec": 120, "required": True}
        if learning_material is not None:
            server["args"].extend(["--learning-material", str(Path(learning_material).resolve())])
        config.append(f"[mcp_servers.{server_name(manifest)}]")
        config.extend(f"{key} = {_toml(value)}" for key, value in server.items())
    role_paths = {}
    for role in roles:
        instructions = role_body(adapter, role)
        role_text = "\n".join(f"{key} = {json.dumps(value, ensure_ascii=False)}" for key, value in {
            "name": role["name"], "description": role["description"], "developer_instructions": instructions}.items()) + "\n"
        tomllib.loads(role_text)
        target = agents_dir / f"{role['name']}.toml"
        target.write_text(role_text)
        role_paths[role["name"]] = str(target)
        config.extend(["", f"[agents.{role['name']}]", f"description = {json.dumps(role['description'], ensure_ascii=False)}",
                       f"config_file = {json.dumps('agents/' + role['name'] + '.toml')}"])
    config_text = "\n".join(config) + "\n"
    tomllib.loads(config_text)
    (output / ".codex" / "config.toml").write_text(config_text)
    context_path.write_text(context_text)
    retire_roles(output, previous, role_paths)
    skills = copy_skills(adapter, manifest, output / ".codex" / "skills")
    result = {"host": "codex", "adapter_id": manifest["id"], "version": manifest["version"], "adapter": str(adapter),
              "workspace": str(output), "context_injected_via": "AGENTS.md",
              "server_name": server_name(manifest) if has_tools else None, "server": server, "roles": role_paths,
              "role_name_map": role_name_map, "skills_dir": str(output / ".codex" / "skills") if skills else None,
              "skills": skills, "audit_log": str(audit) if has_tools else None}
    (output / MARKER).write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n")
    return result


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--adapter", type=Path, required=True)
    parser.add_argument("--workspace", "--output", dest="workspace", type=Path, required=True)
    parser.add_argument("--python", default=sys.executable)
    args = parser.parse_args()
    # Keep a venv interpreter's path; resolve() would follow its symlink out of the venv.
    print(json.dumps(prepare(args.adapter, args.workspace, str(Path(args.python).absolute())), ensure_ascii=False, indent=2))
