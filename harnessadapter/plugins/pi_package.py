"""Emit a Pi package.

Pi discovers `skills/`, `extensions/`, `prompts/` and `themes/` under a package root, and installs a package
from a local path. It does not read MCP servers from a package: those come from `~/.pi/agent/mcp.json` or a
project's `.pi/mcp.json`. The tools are therefore written as a separate `mcp.json` the installer merges, and
the exact command is printed in the README instead of being silently left out.

Pi's subagents are a third-party extension rather than a built-in, with competing formats. An adapter that
exports roles is refused here rather than shipped without them.
"""
from __future__ import annotations

from pathlib import Path

from harnessadapter.plugins.common import (ADAPTER_DIR, AUDIT_LOG, SKILL, Bundle, Unsupported, context_skill,
                                           copy_skills, embed_adapter, load, mcp_entry, write_json)


def build(adapter: Path, output: Path, python: str, *, allow_lossy: bool = False) -> dict:
    bundle = load(adapter, python)
    output = output.resolve()
    if output.exists() and any(output.iterdir()) and not (output / "package.json").is_file():
        raise ValueError("Refusing to write into a nonempty directory this framework did not create")
    if bundle.roles and not allow_lossy:
        raise Unsupported(
            f"Pi has no built-in subagents, but {bundle.id} exports {len(bundle.roles)} role(s): "
            f"{', '.join(r['name'] for r in bundle.roles)}. Pass --allow-lossy to emit the package without "
            "them, or deploy to a host that supports roles.")
    output.mkdir(parents=True, exist_ok=True)

    skills_dir = output / "skills"
    skills = copy_skills(bundle, skills_dir)
    name, body = context_skill(bundle)
    (skills_dir / name).mkdir(parents=True, exist_ok=True)
    (skills_dir / name / SKILL).write_text(body)
    skills = [name] + skills

    embed_adapter(bundle, output)
    write_json(output / "package.json", {
        "name": bundle.id, "version": bundle.version,
        "description": bundle.manifest.get("name", bundle.id), "keywords": ["pi-package"]})

    server = None
    if bundle.has_tools:
        server = mcp_entry(bundle, str(output / ADAPTER_DIR), str(output / AUDIT_LOG))
        write_json(output / "mcp.json", {"mcpServers": {bundle.server: server}})
    (output / "README.md").write_text(_readme(bundle, output, skills, server))
    return {"target": "pi", "adapter_id": bundle.id, "version": bundle.version, "artifact": str(output),
            "skills": skills, "roles": {}, "context_as": f"skill:{name}",
            "server_name": bundle.server if bundle.has_tools else None,
            "mcp_installed_separately": bool(server),
            "omitted": {"roles": [r["name"] for r in bundle.roles]} if bundle.roles else {}}


def _readme(bundle: Bundle, output: Path, skills: list, server) -> str:
    lines = [f"# {bundle.manifest.get('name', bundle.id)} (Pi package)", "",
             f"Generated by `harnessadapter convert` from the `{bundle.id}` adapter, version {bundle.version}.",
             "", "## Install", "```", f"pi install {output}", "```", ""]
    if server:
        lines += ["## Tools", "",
                  "Pi does not read MCP servers from a package, so add the server once:", "```",
                  f"pi mcp add {bundle.server} -- {server['command']} {' '.join(server['args'])}", "```", "",
                  "Then check it with `pi mcp list`, which exits non-zero if the server fails to start.",
                  f"The same entry is written to `mcp.json` in this directory.", ""]
    lines += ["## What is in it", "", f"- Skills: {', '.join(skills)}",
              f"- Context: the skill `{bundle.id}-context`. Pi has no always-on project context from a package,",
              "  so the context is loaded when the skill's description matches.", ""]
    return "\n".join(lines)
