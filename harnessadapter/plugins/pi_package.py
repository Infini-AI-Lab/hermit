"""Emit a Pi package, installed with `pi install <dir>`.

Pi discovers `extensions/`, `skills/`, `prompts/` and `themes/` under a package root. It reads no MCP server from a
package's files, but an extension may register one when it loads (`pi.registerMcpServer`), so the tools ship as a
small generated extension that locates the embedded adapter from its own path.

Pi builds its system prompt from context files in the agent and working directories, never from a package, and has
no built-in subagents. An adapter with a non-empty context or with roles is refused.
"""
from __future__ import annotations

from pathlib import Path
import json

from harnessadapter.plugins.common import (ADAPTER_DIR, AUDIT_LOG, SERVER_COMMAND, copy_skills, embed_adapter, load,
                                           prepare_output, refuse, write_json)

EXTENSION = """\
// Generated by harnessadapter convert: start the adapter's tools when Pi loads this package.
import type {{ ExtensionAPI }} from "@earendil-works/pi-coding-agent";
import {{ dirname, join }} from "node:path";
import {{ fileURLToPath }} from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

export default function (pi: ExtensionAPI) {{
  pi.registerMcpServer({server}, {{
    command: {command},
    args: ["--adapter", join(root, {adapter}), "--audit-log", join(root, {audit})],
  }});
}}
"""


def build(adapter: Path, output: Path, python: str, *, allow_lossy: bool = False) -> dict:
    bundle = load(adapter, python)
    reasons = {}
    if bundle.has_context:
        reasons["context"] = "Pi reads context files from the agent and working directories, not from a package"
    if bundle.roles:
        reasons["roles"] = (f"Pi has no built-in subagents ({', '.join(r['name'] for r in bundle.roles)})")
    omitted = refuse(bundle, "Pi", reasons, allow_lossy=allow_lossy)
    output = prepare_output(output, bundle.adapter, "package.json")

    write_json(output / "package.json", {
        "name": bundle.id, "version": bundle.version, "description": bundle.name, "keywords": ["pi-package"]})
    skills = copy_skills(bundle, output / "skills")
    embed_adapter(bundle, output)
    if bundle.tools:
        (output / "extensions").mkdir(exist_ok=True)
        (output / "extensions" / f"{bundle.id}.ts").write_text(EXTENSION.format(
            server=json.dumps(bundle.server), command=json.dumps(SERVER_COMMAND),
            adapter=json.dumps(ADAPTER_DIR), audit=json.dumps(AUDIT_LOG)))
    (output / "README.md").write_text("\n".join([
        f"# {bundle.name}", "",
        f"A Pi package generated by `harnessadapter convert` from the `{bundle.id}` adapter, version "
        f"{bundle.version}.", "", "```", f"pi install {output}", "```", "",
        "The tools run as `harnessadapter-mcp`, so `harnessadapter` must be installed and on PATH.", "",
        f"- Skills: {', '.join(skills) or 'none'}", f"- Tools: {', '.join(t['name'] for t in bundle.tools) or 'none'}",
        f"- Left out (--allow-lossy): {', '.join(omitted)}" if omitted else "- Left out: nothing", ""]))
    return {"target": "pi", "adapter_id": bundle.id, "version": bundle.version, "output": str(output),
            "install": [f"pi install {output}"], "skills": skills,
            "server_name": bundle.server if bundle.tools else None, "omitted": omitted}
