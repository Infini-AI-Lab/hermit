"""Emit a native Hermes plugin: `plugin.yaml` plus a `register(ctx)` module.

- context: `ctx.register_system_prompt_section`, frozen into each new session prompt. Hermes bounds one section to
  4,000 characters and drops a longer one with only a log warning, so a longer context is refused here. Hermes also
  drops a section that would take all plugins' sections past 8,000 characters together; that depends on the user's
  other plugins and cannot be checked at conversion time.
- skills: `ctx.register_skill`; they are listed in the prompt's skill index as `<plugin>:<skill>`.
- tools: `ctx.register_tool`, each forwarding to a `harnessadapter serve` process the plugin starts on the first call,
  so the tools run exactly as they do under the other hosts.
- roles: Hermes has no file-defined subagents; an adapter with roles is refused.

The generated `__init__.py` is the same file for every adapter; the adapter-specific parts are data next to it.
"""
from __future__ import annotations

from pathlib import Path
import json

from harnessadapter.plugins.common import copy_skills, embed_adapter, load, prepare_output, refuse, write_json

SECTION_MAX_CHARS = 4_000
SECTION_MARKERS = ("<!-- hermes-plugin-sections:start -->", "<!-- hermes-plugin-sections:end -->")

MODULE = '''\
"""Generated by harnessadapter convert: a harness adapter as a native Hermes plugin.

The context, the skills and the tool list are files next to this one. The tools run in one `harnessadapter serve`
process, started on the first call and reused for the session.
"""
import json
from pathlib import Path
import shutil
import subprocess
import threading

ROOT = Path(__file__).resolve().parent
META = json.loads((ROOT / "harnessadapter.json").read_text())


def _data_dir():
    try:
        from plugins.plugin_storage import plugin_data_dir
        return plugin_data_dir(META["plugin"])
    except Exception:
        return ROOT


class _Server:
    def __init__(self):
        self._proc = None
        self._log = None
        self._id = 0
        self._lock = threading.Lock()

    def _send(self, message):
        self._proc.stdin.write(json.dumps(message) + "\\n")
        self._proc.stdin.flush()

    def _request(self, method, params):
        self._id += 1
        self._send({"jsonrpc": "2.0", "id": self._id, "method": method, "params": params})
        while True:
            line = self._proc.stdout.readline()
            if not line:
                raise RuntimeError(f"harnessadapter serve exited; its log is {self._log}")
            message = json.loads(line)
            if message.get("id") == self._id:
                if "error" in message:
                    raise RuntimeError(message["error"].get("message", str(message["error"])))
                return message["result"]

    def _start(self):
        command = shutil.which("harnessadapter")
        if command is None:
            raise RuntimeError("harnessadapter is not on PATH: install it to run this plugin's tools")
        data = Path(_data_dir())
        data.mkdir(parents=True, exist_ok=True)
        self._log = data / "mcp-server.log"
        self._proc = subprocess.Popen(
            [command, "serve", str(ROOT / "adapter"), "--audit-log", str(data / "tool-calls.jsonl")],
            stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=open(self._log, "a"), text=True, bufsize=1)
        self._request("initialize", {"protocolVersion": "2025-06-18", "capabilities": {},
                                     "clientInfo": {"name": "hermes-" + META["plugin"], "version": META["version"]}})
        self._send({"jsonrpc": "2.0", "method": "notifications/initialized"})

    def call(self, tool, arguments):
        with self._lock:
            if self._proc is None or self._proc.poll() is not None:
                self._start()
            result = self._request("tools/call", {"name": tool, "arguments": arguments})
        texts = [item["text"] for item in result.get("content", []) if item.get("type") == "text"]
        return "\\n".join(texts) if texts else json.dumps(result.get("structuredContent", result), ensure_ascii=False)


_SERVER = _Server()


def _handler(tool):
    def handle(args, **kwargs):
        return _SERVER.call(tool, dict(args or {}))
    return handle


def register(ctx):
    context = ROOT / "context.md"
    if context.is_file():
        ctx.register_system_prompt_section(META["plugin"], context.read_text())
    skills = ROOT / "skills"
    if skills.is_dir():
        for child in sorted(skills.iterdir()):
            if (child / "SKILL.md").is_file():
                ctx.register_skill(child.name, child / "SKILL.md")
    for tool in META["tools"]:
        ctx.register_tool(name=tool["hermes_name"], toolset=META["toolset"],
                          schema={"name": tool["hermes_name"], "description": tool["description"],
                                  "parameters": tool["input_schema"]},
                          handler=_handler(tool["name"]))
'''


def build(adapter: Path, output: Path, python: str, *, allow_lossy: bool = False) -> dict:
    bundle = load(adapter, python)
    context = bundle.context.strip()
    reasons = {}
    if len(context) > SECTION_MAX_CHARS:
        reasons["context"] = (f"Hermes drops a plugin's system prompt section over {SECTION_MAX_CHARS:,} characters "
                              f"without an error, and this context has {len(context):,}")
    elif any(marker in context for marker in SECTION_MARKERS):
        reasons["context"] = "it contains a marker Hermes reserves, and Hermes drops such a section"
    if bundle.roles:
        reasons["roles"] = f"Hermes has no file-defined subagents ({', '.join(r['name'] for r in bundle.roles)})"
    omitted = refuse(bundle, "Hermes", reasons, allow_lossy=allow_lossy)
    output = prepare_output(output, bundle.adapter, "plugin.yaml")

    tools = [{"name": t["name"], "hermes_name": f"{bundle.server}_{t['name']}", "description": t["description"],
              "input_schema": t["input_schema"]} for t in bundle.tools]
    (output / "plugin.yaml").write_text(
        f"name: {bundle.id}\nversion: {json.dumps(bundle.version)}\ndescription: {json.dumps(bundle.name)}\n"
        + (f"provides_tools: [{', '.join(t['hermes_name'] for t in tools)}]\n" if tools else ""))
    (output / "__init__.py").write_text(MODULE)
    write_json(output / "harnessadapter.json", {"plugin": bundle.id, "version": bundle.version,
                                                "toolset": bundle.server, "tools": tools})
    context_file = output / "context.md"
    if bundle.has_context and "context" not in omitted:
        context_file.write_text(context + "\n")
    elif context_file.exists():
        context_file.unlink()
    skills = copy_skills(bundle, output / "skills")
    embed_adapter(bundle, output)
    (output / "README.md").write_text("\n".join([
        f"# {bundle.name}", "",
        f"A native Hermes plugin generated by `harnessadapter convert` from the `{bundle.id}` adapter, version "
        f"{bundle.version}.", "", "```", f"cp -r {output} ~/.hermes/plugins/{bundle.id}",
        f"hermes plugins enable {bundle.id}", "```", "",
        "The tools run as `harnessadapter serve`, so `harnessadapter` must be installed and on PATH. Its log and the "
        "tool-call audit log are in the plugin's data directory.", "",
        f"- Context: a system prompt section of {len(context):,} characters. Hermes drops it, with a log warning, when "
        f"all plugins' sections together would pass 8,000 characters." if context_file.exists() else "- Context: none",
        f"- Skills: {', '.join(skills) or 'none'}",
        f"- Tools: {', '.join(t['hermes_name'] for t in tools) or 'none'}",
        f"- Left out (--allow-lossy): {', '.join(omitted)}" if omitted else "- Left out: nothing", ""]))
    return {"target": "hermes", "adapter_id": bundle.id, "version": bundle.version, "output": str(output),
            "install": [f"cp -r {output} ~/.hermes/plugins/{bundle.id}", f"hermes plugins enable {bundle.id}"],
            "context_chars": len(context) if context_file.exists() else 0, "skills": skills,
            "tools": [t["hermes_name"] for t in tools], "omitted": omitted}
