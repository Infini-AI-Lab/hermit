"""Emit a native Hermes plugin: `plugin.yaml` plus a `register(ctx)` module.

- context: `ctx.register_system_prompt_section`, frozen into each new session prompt. Hermes bounds one section to
  4,000 characters and drops a longer one with only a log warning, so a longer context is refused here. Hermes also
  drops a section that would take all plugins' sections past 8,000 characters together; that depends on the user's
  other plugins and cannot be checked at conversion time.
- skills: `ctx.register_skill`; they are listed in the prompt's skill index as `<plugin>:<skill>`.
- tools: `ctx.register_tool`, each forwarding to a `harnessadapter serve` process the plugin starts on the first call,
  so the tools run exactly as they do under the other hosts.
- roles: Hermes has no file-defined subagents; an adapter with roles is refused.

The plugin's `__init__.py` is `hermes/plugin_init.py`, the same file for every adapter; the adapter-specific parts
are data next to it.
"""
from __future__ import annotations

from pathlib import Path
import json
import shutil

from harnessadapter.plugins.common import (FRAMEWORK_VERSION, RECORD, clear, copy_skills, embed_adapter, load,
                                           prepare_output, record, refuse)

SECTION_MAX_CHARS = 4_000
SECTION_MARKERS = ("<!-- hermes-plugin-sections:start -->", "<!-- hermes-plugin-sections:end -->")

# Copied unchanged into every emitted plugin as its `__init__.py`.
PLUGIN_INIT = Path(__file__).parent / "hermes" / "plugin_init.py"


def build(adapter: Path, output: Path, python: str, *, allow_lossy: bool = False) -> dict:
    bundle = load(adapter, python)
    context = bundle.context.strip()
    reasons = {}
    if len(context) > SECTION_MAX_CHARS:
        reasons["context"] = (f"Hermes drops a plugin's system prompt section over {SECTION_MAX_CHARS:,} characters "
                              f"without an error, and this context has {len(context):,}")
    elif any(marker in context for marker in SECTION_MARKERS):
        reasons["context"] = "it contains a marker Hermes reserves, and Hermes drops such a section"
    if bundle.roles:
        reasons["roles"] = f"Hermes has no file-defined subagents ({', '.join(r['name'] for r in bundle.roles)})"
    omitted = refuse(bundle, "Hermes", reasons, allow_lossy=allow_lossy)
    output = prepare_output(output, bundle.adapter, RECORD)
    clear(output, "skills", "context.md")

    tools = [{"name": t["name"], "hermes_name": f"{bundle.server}_{t['name']}", "description": t["description"],
              "input_schema": t["input_schema"]} for t in bundle.tools]
    (output / "plugin.yaml").write_text(
        f"name: {bundle.id}\nversion: {json.dumps(bundle.version)}\ndescription: {json.dumps(bundle.name)}\n"
        + (f"provides_tools: [{', '.join(t['hermes_name'] for t in tools)}]\n" if tools else ""))
    shutil.copyfile(PLUGIN_INIT, output / "__init__.py")
    record(bundle, output, toolset=bundle.server, tools=tools)
    context_file = output / "context.md"
    if bundle.has_context and "context" not in omitted:
        context_file.write_text(context + "\n")
    skills = copy_skills(bundle, output / "skills")
    embed_adapter(bundle, output)
    (output / "README.md").write_text("\n".join([
        f"# {bundle.name}", "",
        f"A native Hermes plugin generated by `harnessadapter convert` from the `{bundle.id}` adapter, version "
        f"{bundle.version}.", "", "```", f"cp -r {output} ~/.hermes/plugins/{bundle.id}",
        f"hermes plugins enable {bundle.id}", "```", "",
        "The tools run as `harnessadapter serve`, so `harnessadapter` must be installed and on PATH. Its log and the "
        "tool-call audit log are in the plugin's data directory.", "",
        f"- Context: a system prompt section of {len(context):,} characters. Hermes drops it, with a log warning, when "
        f"all plugins' sections together would pass 8,000 characters." if context_file.exists() else "- Context: none",
        f"- Skills: {', '.join(skills) or 'none'}",
        f"- Tools: {', '.join(t['hermes_name'] for t in tools) or 'none'}",
        f"- Left out (--allow-lossy): {', '.join(omitted)}" if omitted else "- Left out: nothing", ""]))
    return {"target": "hermes", "adapter_id": bundle.id, "version": bundle.version, "framework": FRAMEWORK_VERSION,
            "output": str(output),
            "install": [f"cp -r {output} ~/.hermes/plugins/{bundle.id}", f"hermes plugins enable {bundle.id}"],
            "context_chars": len(context) if context_file.exists() else 0, "skills": skills,
            "tools": [t["hermes_name"] for t in tools], "omitted": omitted}
