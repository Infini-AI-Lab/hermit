"""Emit a Codex plugin, inside a local marketplace that `codex plugin marketplace add` accepts.

Codex's primary plugin format is an Agent Plugins v1 package: `plugin.json` at the plugin root, a fixed `skills/`
directory and a root `mcp.json` (`.codex-plugin/plugin.json` is only a compatibility fallback, and does not expand
`${PLUGIN_ROOT}`). Codex expands `${PLUGIN_ROOT}` and `${PLUGIN_DATA}` in `mcp.json`, so the tool entry stays valid
wherever the plugin is installed.

The format carries skills and tools only. Codex reads no instruction file and no subagent from a plugin, so an
adapter with a non-empty context or with roles is refused.
"""
from __future__ import annotations

from pathlib import Path

from harnessadapter.plugins.common import (ADAPTER_DIR, AUDIT_LOG, FRAMEWORK_VERSION, SERVER_COMMAND, clear, copy_skills,
                                           embed_adapter, load, prepare_output, record, refuse, server_args, write_json)

PLUGIN_SCHEMA = "https://agent-plugins.org/schemas/1.0.0/plugin.schema.json"
MCP_SCHEMA = "https://agent-plugins.org/schemas/1.0.0/mcp.schema.json"
MARKETPLACE = ".agents/plugins/marketplace.json"


def build(adapter: Path, output: Path, python: str, *, allow_lossy: bool = False) -> dict:
    bundle = load(adapter, python)
    reasons = {}
    if bundle.has_context:
        reasons["context"] = "Codex reads no AGENTS.md or other instruction file from a plugin"
    if bundle.roles:
        reasons["roles"] = (f"Codex loads no subagent from a plugin ({', '.join(r['name'] for r in bundle.roles)}); "
                            "`harnessadapter deploy --host codex` registers them in a workspace")
    omitted = refuse(bundle, "Codex", reasons, allow_lossy=allow_lossy)
    output = prepare_output(output, bundle.adapter, MARKETPLACE)
    plugin = output / "plugins" / bundle.id
    plugin.mkdir(parents=True, exist_ok=True)
    clear(plugin, "skills", "mcp.json")

    write_json(output / MARKETPLACE, {
        "name": f"{bundle.id}-adapters", "interface": {"displayName": bundle.name},
        "plugins": [{"name": bundle.id, "source": {"source": "local", "path": f"./plugins/{bundle.id}"}}]})
    write_json(plugin / "plugin.json", {
        "$schema": PLUGIN_SCHEMA, "name": bundle.id, "version": bundle.version, "description": bundle.name})
    skills = copy_skills(bundle, plugin / "skills")
    embed_adapter(bundle, plugin)
    record(bundle, plugin)
    if bundle.tools:
        write_json(plugin / "mcp.json", {"$schema": MCP_SCHEMA, "mcpServers": {bundle.server: {
            "type": "stdio", "command": SERVER_COMMAND,
            "args": server_args(f"${{PLUGIN_ROOT}}/{ADAPTER_DIR}", f"${{PLUGIN_DATA}}/{AUDIT_LOG}")}}})
    (plugin / "README.md").write_text("\n".join([
        f"# {bundle.name}", "",
        f"A Codex plugin generated by `harnessadapter convert` from the `{bundle.id}` adapter, version "
        f"{bundle.version}.", "", "```", f"codex plugin marketplace add {output}",
        f"codex plugin add {bundle.id}@{bundle.id}-adapters", "```", "",
        "The tools run as `harnessadapter serve`, so `harnessadapter` must be installed and on PATH.", "",
        f"- Skills: {', '.join(skills) or 'none'}", f"- Tools: {', '.join(t['name'] for t in bundle.tools) or 'none'}",
        f"- Left out (--allow-lossy): {', '.join(omitted)}" if omitted else "- Left out: nothing", ""]))
    return {"target": "codex", "adapter_id": bundle.id, "version": bundle.version, "framework": FRAMEWORK_VERSION,
            "output": str(output),
            "plugin": str(plugin), "install": [f"codex plugin marketplace add {output}",
                                               f"codex plugin add {bundle.id}@{bundle.id}-adapters"],
            "skills": skills, "server_name": bundle.server if bundle.tools else None, "omitted": omitted}
