"""Emit a source tree for `hermes import-agent claude-code --source <dir>/.claude`.

Hermes has no plugin system. It has an importer that reads another agent's configuration directory and maps it
onto its own: `CLAUDE.md` becomes memory entries, `mcpServers` become `config.yaml` entries, and
`skills/<name>/` become `skills/claude-code-imports/<name>/`. The importer takes `--source`, so the tree does
not have to be the user's real `~/.claude`.

Two properties of that importer shape this emitter. It reads `mcpServers` from `.claude.json` *next to* the
source directory, so that file is written one level up. And it ignores `agents/` entirely -- not reported as
skipped, simply absent from the result -- so an adapter that exports roles is refused here: Hermes would not
tell the user that the roles never arrived.
"""
from __future__ import annotations

from pathlib import Path

from harnessadapter.plugins.common import (ADAPTER_DIR, AUDIT_LOG, SKILL, Bundle, Unsupported, context_skill,
                                           copy_skills, embed_adapter, load, mcp_entry, write_json)


def build(adapter: Path, output: Path, python: str, *, allow_lossy: bool = False) -> dict:
    bundle = load(adapter, python)
    output = output.resolve()
    if output.exists() and any(output.iterdir()) and not (output / ".claude").is_dir():
        raise ValueError("Refusing to write into a nonempty directory this framework did not create")
    if bundle.roles and not allow_lossy:
        raise Unsupported(
            f"`hermes import-agent` silently drops subagents, and {bundle.id} exports "
            f"{len(bundle.roles)} role(s): {', '.join(r['name'] for r in bundle.roles)}. Hermes would import "
            "everything else and never report the roles missing. Pass --allow-lossy to accept that, or deploy "
            "to a host that supports roles.")
    source = output / ".claude"
    source.mkdir(parents=True, exist_ok=True)

    skills = copy_skills(bundle, source / "skills")
    name, body = context_skill(bundle)
    (source / "skills" / name).mkdir(parents=True, exist_ok=True)
    (source / "skills" / name / SKILL).write_text(body)
    skills = [name] + skills
    # The context also goes in as CLAUDE.md: the importer turns it into memory entries, which unlike a skill
    # are always present. This is the one target where the adapter's context keeps its always-on character.
    (source / "CLAUDE.md").write_text(bundle.context.strip() + "\n")

    embed_adapter(bundle, output)
    server = None
    if bundle.has_tools:
        server = mcp_entry(bundle, str(output / ADAPTER_DIR), str(output / AUDIT_LOG))
    # Next to the source directory, where the importer looks for it.
    write_json(output / ".claude.json", {"mcpServers": {bundle.server: server} if server else {}})
    (output / "README.md").write_text(_readme(bundle, output, skills, bool(server)))
    return {"target": "hermes", "adapter_id": bundle.id, "version": bundle.version, "artifact": str(output),
            "source": str(source), "skills": skills, "roles": {}, "context_as": "memory:CLAUDE.md",
            "server_name": bundle.server if bundle.has_tools else None,
            "import_command": f"hermes import-agent claude-code --source {source}",
            "omitted": {"roles": [r["name"] for r in bundle.roles]} if bundle.roles else {}}


def _readme(bundle: Bundle, output: Path, skills: list, has_tools: bool) -> str:
    lines = [f"# {bundle.manifest.get('name', bundle.id)} (Hermes import source)", "",
             f"Generated by `harnessadapter convert` from the `{bundle.id}` adapter, version {bundle.version}.",
             "", "## Import", "```",
             f"hermes import-agent claude-code --source {output / '.claude'} --dry-run",
             f"hermes import-agent claude-code --source {output / '.claude'}", "```", "",
             "Run the `--dry-run` first: it prints exactly what would be written into `HERMES_HOME`.", "",
             "## What is imported", "", f"- Skills: {', '.join(skills)} -> `skills/claude-code-imports/`",
             "- Context: `CLAUDE.md` -> memory entries, which are always present.",
             ("- Tools: the MCP server -> `config.yaml`. Hermes strips environment variables whose names look "
              "like credentials." if has_tools else "- Tools: none."), "",
             "This is an import, not an installation: it writes into the global `HERMES_HOME` and there is no",
             "uninstall. `hermes import-agent --sync` re-imports this directory after it is regenerated.", ""]
    return "\n".join(lines)
